# Ensure unique entries (case-insensitive for key)
seen = set()
unique_entries = []
for k, v in entries:
    k_clean = k.strip()
    k_lower = k_clean.lower()
    if k_lower not in seen:
        seen.add(k_lower)
        unique_entries.append((k_clean, v.strip()))

# Sort: longer keys first so multi-word expressions are matched first, then alphabetical
unique_entries.sort(key=lambda item: (-len(item[0].split()), -len(item[0]), item[0].lower()))

output_path = os.path.join("app", "src", "main", "assets", "tts_en_vi_dict.tsv")
os.makedirs(os.path.dirname(output_path), exist_ok=True)

with open(output_path, "w", encoding="utf-8") as f:
    f.write("# Nuvio TV English to Vietnamese Phonetic Dictionary\n")
    f.write("# Format: english_word_or_phrase<TAB>vietnamese_phonetic\n")
    for k, v in unique_entries:
        f.write(f"{k}\t{v}\n")

print(f"Generated {len(unique_entries)} entries into {output_path}")
